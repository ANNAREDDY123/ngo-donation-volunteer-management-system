
from datetime import datetime, timezone

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from app.models.notification import Notification, NotificationType
from app.models.user import User
from app.schemas.notification import NotificationCreate


def utc_now():
    return datetime.now(timezone.utc)


def create_notification(
    db: Session,
    user_id: int,
    title: str,
    message: str,
    notification_type: NotificationType = NotificationType.GENERAL,
    related_entity_type: str | None = None,
    related_entity_id: int | None = None,
) -> Notification:
    """Reusable helper for notifications generated by other modules."""
    if db.get(User, user_id) is None:
        raise ValueError("User not found")

    title = title.strip()
    message = message.strip()

    if not title or not message:
        raise ValueError("Notification title and message cannot be empty")

    notification = Notification(
        user_id=user_id,
        title=title,
        message=message,
        notification_type=notification_type,
        related_entity_type=related_entity_type,
        related_entity_id=related_entity_id,
    )
    db.add(notification)
    db.commit()
    db.refresh(notification)
    return notification


def create_notification_from_payload(
    db: Session,
    payload: NotificationCreate,
) -> Notification:
    return create_notification(
        db=db,
        user_id=payload.user_id,
        title=payload.title,
        message=payload.message,
        notification_type=payload.notification_type,
        related_entity_type=payload.related_entity_type,
        related_entity_id=payload.related_entity_id,
    )


def get_notification_for_user(
    db: Session,
    notification_id: int,
    user_id: int,
) -> Notification:
    notification = db.get(Notification, notification_id)

    if notification is None or notification.user_id != user_id:
        raise ValueError("Notification not found")

    return notification


def list_user_notifications(
    db: Session,
    user_id: int,
    unread_only: bool = False,
    notification_type: NotificationType | None = None,
    skip: int = 0,
    limit: int = 20,
) -> dict:
    conditions = [Notification.user_id == user_id]

    if unread_only:
        conditions.append(Notification.is_read.is_(False))

    if notification_type is not None:
        conditions.append(
            Notification.notification_type == notification_type
        )

    query = (
        select(Notification)
        .where(*conditions)
        .order_by(Notification.created_at.desc(), Notification.id.desc())
    )

    total = db.scalar(
        select(func.count(Notification.id)).where(*conditions)
    ) or 0

    unread_count = db.scalar(
        select(func.count(Notification.id)).where(
            Notification.user_id == user_id,
            Notification.is_read.is_(False),
        )
    ) or 0

    items = db.scalars(query.offset(skip).limit(limit)).all()

    return {
        "items": items,
        "total": total,
        "unread_count": unread_count,
        "skip": skip,
        "limit": limit,
    }


def mark_notification_read(
    db: Session,
    notification_id: int,
    user_id: int,
) -> Notification:
    notification = get_notification_for_user(db, notification_id, user_id)

    if not notification.is_read:
        notification.is_read = True
        notification.read_at = utc_now()
        db.commit()
        db.refresh(notification)

    return notification


def mark_all_notifications_read(db: Session, user_id: int) -> int:
    notifications = db.scalars(
        select(Notification).where(
            Notification.user_id == user_id,
            Notification.is_read.is_(False),
        )
    ).all()

    now = utc_now()
    for notification in notifications:
        notification.is_read = True
        notification.read_at = now

    if notifications:
        db.commit()

    return len(notifications)


def delete_notification(
    db: Session,
    notification_id: int,
    user_id: int,
) -> None:
    notification = get_notification_for_user(db, notification_id, user_id)
    db.delete(notification)
    db.commit()
